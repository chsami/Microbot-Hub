package net.runelite.client.plugins.microbot.cgprep.boss;

/**
 * The damaging-floor patterns and timings, read off 140 floor cycles in 7 recorded Corrupted fights
 * (arena-relative; row y = 0 first, '#' = tile in the pattern). The patterns are fixed shapes, not
 * aimed at the player (the player was inside only 25% of them).
 *
 * Timing per cycle: tiles WARN (crimson), then HIT (orange: 10-20 damage every tick you stand on
 * one) for twice as long, and the next pattern warns the tick the last one clears:
 *   phase 1 (boss HP > 666): warn 7, hit 14 (cycle 21; the fight's first warning lasts 8),
 *   phase 2 (HP > 333):      warn 5, hit 10 (cycle 15),
 *   phase 3:                 warn 3, hit  6 (cycle 9).
 * The warn length follows the phase when the warning appears, the hit length the phase when the
 * hit starts (a pattern that warned in phase 1 and hit in phase 2 lasted 7 + 10).
 * The first warning comes 4 ticks after the boss's first attack. Each new pattern is drawn from its
 * phase's list, never the same one twice in a row.
 */
